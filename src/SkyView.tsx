import { useEffect, useRef } from 'react';
import * as THREE from 'three';
import { PrecomputedTexturesGenerator, SkyMaterial } from '@takram/three-atmosphere';
import type { Sim, Solar } from './physics';
import { earthRadiusAt, FT_TO_M, SUN_RADIUS_DEG } from './physics';
import { compositeFragment, screenVertex } from './renderShaders';
import type { RunwayEnd } from './flightPlan';

export type Quality = 'low' | 'medium' | 'high' | 'ultra';
export type CloudCover = 'clear' | 'few' | 'scattered' | 'broken' | 'overcast';
export type ViewMode = 'eye' | 'camera';
type Props = { state: Sim; solar: Solar; cameraAz: number; cameraEl: number; quality: Quality; clouds: CloudCover; mode: ViewMode; exposure: number; fov: number; runway?: RunwayEnd };
type Engine = { renderer: THREE.WebGLRenderer; scene: THREE.Scene; camera: THREE.PerspectiveCamera; sky: SkyMaterial; composite: THREE.ShaderMaterial; target: THREE.WebGLRenderTarget; screen: THREE.Scene; screenCam: THREE.Camera; generator: PrecomputedTexturesGenerator; landMask: THREE.Texture; earthColor: THREE.Texture; cloudVolume: THREE.Texture; frame: number; lastFrame: number; frames: number; lastSample: number; slowSamples: number; degraded: boolean; quality: Quality; resize: () => void };
const coverValues: Record<CloudCover,number> = { clear:0, few:.32, scattered:.82, broken:.93, overcast:.98 };
const pixelRatios: Record<Quality,number> = { low:.70, medium:.80, high:1.10, ultra:1.5 };
const cloudSteps: Record<Quality,number> = { low:6, medium:9, high:16, ultra:22 };
const RAD = Math.PI/180;
export function SkyView({ state, solar, cameraAz, cameraEl, quality, clouds, mode, exposure, fov, runway }: Props) {
 const host = useRef<HTMLDivElement>(null);
 const engine = useRef<Engine|null>(null);
 useEffect(()=>{
  const el=host.current; if(!el)return;
  el.dataset.ready='false';
  let disposed=false;
  const renderer=new THREE.WebGLRenderer({antialias:false,powerPreference:'high-performance',alpha:false});
  renderer.setPixelRatio(Math.min(devicePixelRatio,pixelRatios[quality]));
  renderer.outputColorSpace=THREE.SRGBColorSpace;
  renderer.toneMapping=THREE.NoToneMapping;
  renderer.setSize(el.clientWidth,el.clientHeight);
  el.appendChild(renderer.domElement);
  const camera=new THREE.PerspectiveCamera(fov,el.clientWidth/el.clientHeight,.1,1000);
  const scene=new THREE.Scene();
  const sky=new SkyMaterial({moon:false,ground:true,groundAlbedo:new THREE.Color().setRGB(.035,.075,.095),sunAngularRadius:SUN_RADIUS_DEG*RAD});
  const skyQuad=new THREE.Mesh(new THREE.PlaneGeometry(2,2),sky);skyQuad.frustumCulled=false;scene.add(skyQuad);
  const target=new THREE.WebGLRenderTarget(Math.max(1,el.clientWidth),Math.max(1,el.clientHeight),{type:THREE.HalfFloatType,format:THREE.RGBAFormat,depthBuffer:false,stencilBuffer:false});
  target.texture.colorSpace=THREE.LinearSRGBColorSpace;
  const landMask=new THREE.TextureLoader().load(`${import.meta.env.BASE_URL}landmask.png`);
  landMask.colorSpace=THREE.NoColorSpace;
  landMask.wrapS=THREE.RepeatWrapping;
  landMask.minFilter=THREE.LinearFilter;
  const earthColor=new THREE.TextureLoader().load(`${import.meta.env.BASE_URL}earth-color.jpg`);
  earthColor.colorSpace=THREE.SRGBColorSpace;
  earthColor.wrapS=THREE.RepeatWrapping;
  earthColor.minFilter=THREE.LinearMipmapLinearFilter;
  const cloudVolume=new THREE.TextureLoader().load(`${import.meta.env.BASE_URL}cloud-volume.png`);
  cloudVolume.colorSpace=THREE.NoColorSpace;
  cloudVolume.flipY=false;
  cloudVolume.generateMipmaps=false;
  cloudVolume.minFilter=THREE.LinearFilter;
  cloudVolume.magFilter=THREE.LinearFilter;
  const composite=new THREE.ShaderMaterial({vertexShader:screenVertex,fragmentShader:compositeFragment,depthTest:false,depthWrite:false,defines:{CLOUD_STEPS:cloudSteps[quality]},uniforms:{uSky:{value:target.texture},uLandMask:{value:landMask},uEarthColor:{value:earthColor},uCloudVolume:{value:cloudVolume},uInvProjection:{value:new THREE.Matrix4()},uCameraWorld:{value:new THREE.Matrix4()},uEcef:{value:new THREE.Vector3()},uEast:{value:new THREE.Vector3()},uUp:{value:new THREE.Vector3()},uSouth:{value:new THREE.Vector3()},uSun:{value:new THREE.Vector3(0,0,-1)},uRunwayOrigin:{value:new THREE.Vector3()},uRunwayForward:{value:new THREE.Vector3()},uRunwaySide:{value:new THREE.Vector3()},uRunwayLength:{value:0},uAltitude:{value:0},uRadius:{value:6371000},uTime:{value:0},uCoverage:{value:.48},uExposure:{value:1},uEye:{value:1},uHorizonUV:{value:.5},uResolution:{value:new THREE.Vector2(1,1)},uCloudStepBudget:{value:cloudSteps[quality]}}});
  const screen=new THREE.Scene(),screenCam=new THREE.Camera();screenCam.position.z=1;
  const finalQuad=new THREE.Mesh(new THREE.PlaneGeometry(2,2),composite);finalQuad.frustumCulled=false;screen.add(finalQuad);
  const resize=()=>{const w=Math.max(1,el.clientWidth),h=Math.max(1,el.clientHeight);camera.aspect=w/h;camera.updateProjectionMatrix();renderer.setSize(w,h);const size=new THREE.Vector2();renderer.getDrawingBufferSize(size);target.setSize(size.x,size.y);composite.uniforms.uResolution.value.copy(size);};
  const observer=new ResizeObserver(resize);observer.observe(el);resize();
  const generator=new PrecomputedTexturesGenerator(renderer);
  generator.update().then(textures=>{if(disposed)return;Object.assign(sky,textures);el.dataset.ready='true';}).catch(error=>{if(!disposed){console.error('Atmosphere LUT generation failed',error);el.dataset.renderError='atmosphere-lut';}});
  const e:Engine={renderer,scene,camera,sky,composite,target,screen,screenCam,generator,landMask,earthColor,cloudVolume,frame:0,lastFrame:performance.now(),frames:0,lastSample:performance.now(),slowSamples:0,degraded:false,quality,resize};engine.current=e;
  const tick=(now:number)=>{if(disposed)return;e.camera.updateMatrixWorld();composite.uniforms.uInvProjection.value.copy(e.camera.projectionMatrixInverse);composite.uniforms.uCameraWorld.value.copy(e.camera.matrixWorld);renderer.setRenderTarget(target);renderer.render(scene,camera);renderer.setRenderTarget(null);renderer.render(screen,screenCam);e.frames++;if(now-e.lastSample>1000){const fps=e.frames*1000/(now-e.lastSample);el.dataset.fps=String(Math.round(fps));if(el.dataset.ready==='true'&&!e.degraded){e.slowSamples=fps<28?e.slowSamples+1:0;if(e.slowSamples>=3){e.degraded=true;el.dataset.adaptive='reduced';renderer.setPixelRatio(Math.max(.6,renderer.getPixelRatio()*.75));composite.uniforms.uCloudStepBudget.value=Math.max(3,Math.ceil(cloudSteps[e.quality]*.6));resize();}}e.lastSample=now;e.frames=0;}e.lastFrame=now;e.frame=requestAnimationFrame(tick);};e.frame=requestAnimationFrame(tick);
  return()=>{disposed=true;observer.disconnect();cancelAnimationFrame(e.frame);generator.dispose();skyQuad.geometry.dispose();finalQuad.geometry.dispose();sky.dispose();composite.dispose();landMask.dispose();earthColor.dispose();cloudVolume.dispose();target.dispose();renderer.dispose();el.removeChild(renderer.domElement);engine.current=null;};
 },[]);
 useEffect(()=>{const e=engine.current;if(!e)return;
  if(e.quality!==quality){e.quality=quality;e.degraded=false;e.slowSamples=0;if(host.current)delete host.current.dataset.adaptive;e.renderer.setPixelRatio(Math.min(devicePixelRatio,pixelRatios[quality]));e.composite.defines.CLOUD_STEPS=cloudSteps[quality];e.composite.uniforms.uCloudStepBudget.value=cloudSteps[quality];e.composite.needsUpdate=true;e.resize();}
  const lat=state.lat*RAD,lon=state.lon*RAD,cLat=Math.cos(lat),sLat=Math.sin(lat),cLon=Math.cos(lon),sLon=Math.sin(lon);
  const east=new THREE.Vector3(-sLon,cLon,0),up=new THREE.Vector3(cLat*cLon,cLat*sLon,sLat),north=new THREE.Vector3(-sLat*cLon,-sLat*sLon,cLat);
  const h=state.altitudeFt*FT_TO_M;
  const a=6378137,e2=0.0066943799901413165,N=a/Math.sqrt(1-e2*sLat*sLat);
  const ecef=new THREE.Vector3((N+h)*cLat*cLon,(N+h)*cLat*sLon,(N*(1-e2)+h)*sLat);
  e.sky.worldToECEFMatrix.makeBasis(east,up,north.clone().negate()).setPosition(ecef);
  e.composite.uniforms.uEcef.value.copy(ecef);
  e.composite.uniforms.uEast.value.copy(east);
  e.composite.uniforms.uUp.value.copy(up);
  e.composite.uniforms.uSouth.value.copy(north).negate();
  e.composite.uniforms.uRunwayLength.value=runway?runway.l*FT_TO_M:0;
  if(runway){
   const rLat=runway.p[0]*RAD,rLon=runway.p[1]*RAD,s=Math.sin(rLat),c=Math.cos(rLat),sl=Math.sin(rLon),cl=Math.cos(rLon);
   const rn=a/Math.sqrt(1-e2*s*s);
   const reast=new THREE.Vector3(-sl,cl,0),rnorth=new THREE.Vector3(-s*cl,-s*sl,c);
   const rh=runway.h*RAD;
   e.composite.uniforms.uRunwayOrigin.value.set(rn*c*cl,rn*c*sl,rn*(1-e2)*s);
   e.composite.uniforms.uRunwayForward.value.copy(reast).multiplyScalar(Math.sin(rh)).addScaledVector(rnorth,Math.cos(rh));
   e.composite.uniforms.uRunwaySide.value.copy(reast).multiplyScalar(Math.cos(rh)).addScaledVector(rnorth,-Math.sin(rh));
  }
  const az=solar.azimuth*RAD,alt=solar.apparentElevation*RAD;
  const sunLocal=new THREE.Vector3(Math.sin(az)*Math.cos(alt),Math.sin(alt),-Math.cos(az)*Math.cos(alt));
  e.sky.sunDirection.copy(sunLocal).transformDirection(e.sky.worldToECEFMatrix);
  e.composite.uniforms.uSun.value.copy(sunLocal);
  e.composite.uniforms.uAltitude.value=h;
  e.composite.uniforms.uRadius.value=earthRadiusAt(state.lat,solar.azimuth);
  e.composite.uniforms.uTime.value=state.timeMs/1000;
  e.composite.uniforms.uCoverage.value=coverValues[clouds];
  e.composite.uniforms.uExposure.value=exposure;
  e.composite.uniforms.uEye.value=mode==='eye'?1:0;
  e.camera.fov=fov;e.camera.updateProjectionMatrix();
  const yaw=cameraAz*RAD,pitch=cameraEl*RAD;
  e.camera.lookAt(Math.sin(yaw)*Math.cos(pitch),Math.sin(pitch),-Math.cos(yaw)*Math.cos(pitch));
  const horizon=-solar.horizonDip*RAD;
  e.composite.uniforms.uHorizonUV.value=.5+Math.tan(horizon-pitch)/(2*Math.tan(fov*RAD*.5));
 },[state,solar,cameraAz,cameraEl,clouds,mode,exposure,fov,quality,runway]);
 return <div className="sky" ref={host}><div className="sky-loading">計算大氣散射 LUT…</div></div>;
}
